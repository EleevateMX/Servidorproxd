local T = _G.T
local load = dofile(ROOT .. 'tests/lua/load_gamemodes.lua')

local function arenaCombat()
    return {
        id = 'test', label = 'Test',
        spawns = { { x = 0, y = 0, z = 0, h = 0 } },
        teamSpawns = { { { x = 0, y = 0, z = 0, h = 0 } }, { { x = 50, y = 0, z = 0, h = 180 } } },
        zone = { x = 100, y = 100, z = 10, radius = 15 },
    }
end

local function arenaRace()
    return {
        id = 'circuito', label = 'Circuito',
        grid = { { x = 0, y = 0, z = 0, h = 0 } },
        checkpoints = { { x = 10, y = 0, z = 0 }, { x = 20, y = 0, z = 0 }, { x = 30, y = 0, z = 0 } },
    }
end

T.describe('Modes', function()
    T.it('registra los cuatro modos incluidos', function()
        local P = load()
        T.eq(#P.Modes.order, 4)
        T.truthy(P.Modes.get('ffa') and P.Modes.get('tdm') and P.Modes.get('koth') and P.Modes.get('race'))
    end)
    T.it('rechaza ids inválidos y duplicados', function()
        local P = load()
        T.throws(function() P.Modes.register({ id = 'Mal Id', label = 'x', kind = 'combat' }) end, 'id inválido')
        T.throws(function() P.Modes.register({ id = 'ffa', label = 'x', kind = 'combat' }) end, 'duplicado')
    end)
    T.it('exige forma de terminar la partida', function()
        local P = load()
        T.throws(function()
            P.Modes.register({ id = 'eterno', label = 'x', kind = 'combat', durationSec = 0, scoreLimit = 0 })
        end, 'terminar')
    end)
    T.it('valida que la arena tenga lo que el modo necesita', function()
        local P = load()
        T.truthy(P.Modes.validateArena(P.Modes.get('tdm'), arenaCombat()))
        local ok, err = P.Modes.validateArena(P.Modes.get('race'), arenaCombat())
        T.falsy(ok); T.truthy(err:find('checkpoints'))
        local a = arenaCombat(); a.zone = nil
        T.falsy(P.Modes.validateArena(P.Modes.get('koth'), a))
    end)
end)

T.describe('Match', function()
    T.it('reparte equipos de forma equilibrada', function()
        local P = load()
        local m = P.Match.new({ id = 1, mode = P.Modes.get('tdm'), arena = arenaCombat() })
        for i = 1, 5 do m:join(i, 'p' .. i, 0) end
        local c = m:teamCounts()
        T.eq(c[1], 3); T.eq(c[2], 2)
    end)
    T.it('no deja empezar sin el mínimo de jugadores', function()
        local P = load()
        local m = P.Match.new({ id = 1, mode = P.Modes.get('ffa'), arena = arenaCombat() })
        m:join(1, 'a', 0)
        local ok, err = m:start(0)
        T.falsy(ok); T.truthy(err:find('al menos 2'))
    end)
    T.it('cuenta atrás → en curso → fin por tiempo', function()
        local P = load()
        local m = P.Match.new({ id = 1, mode = P.Modes.get('ffa'), arena = arenaCombat() })
        m:join(1, 'a', 0); m:join(2, 'b', 0)
        T.truthy(m:start(100))
        T.eq(m.state, 'countdown')
        T.eq(#m:tick(105), 0)
        local ev = m:tick(110)
        T.eq(ev[1].type, 'started'); T.eq(m.state, 'running')
        T.eq(m:snapshot(110).timeLeft, 600)
        ev = m:tick(710)
        T.eq(ev[1].type, 'ended'); T.eq(ev[1].reason, 'time')
    end)
    T.it('puntúa bajas, suicidios y fuego amigo', function()
        local P = load()
        local m = P.Match.new({ id = 1, mode = P.Modes.get('tdm'), arena = arenaCombat() })
        m:join(1, 'a', 0); m:join(2, 'b', 0); m:join(3, 'c', 0) -- 1 y 3 en equipo 1
        m:start(0); m:tick(10)
        T.eq(m:registerDeath(2, 1, 11), 'kill')
        T.eq(m:registerDeath(3, 1, 12), 'teamkill')
        T.eq(m:registerDeath(2, nil, 13), 'suicide')
        T.eq(m.players[1].score, 0)   -- +1 -1
        T.eq(m.players[1].kills, 1)
        T.eq(m.players[2].deaths, 2)
        T.eq(m.teamScores[1], 0); T.eq(m.teamScores[2], -1)
    end)
    T.it('termina al llegar al límite de puntos (individual)', function()
        local P = load()
        local m = P.Match.new({ id = 1, mode = P.Modes.get('ffa'), arena = arenaCombat() })
        m:join(1, 'a', 0); m:join(2, 'b', 0)
        m:start(0); m:tick(10)
        local events = {}
        for _ = 1, 20 do m:registerDeath(2, 1, 20, events) end
        T.eq(m.state, 'ended'); T.eq(m.endReason, 'score')
        T.eq(m.winner.type, 'player'); T.eq(m.winner.id, 1)
        T.eq(events[1].type, 'ended')
        T.eq(m:registerDeath(2, 1, 21), nil, 'tras terminar no se puntúa')
    end)
    T.it('ignora muertes de jugadores ajenos a la partida', function()
        local P = load()
        local m = P.Match.new({ id = 1, mode = P.Modes.get('ffa'), arena = arenaCombat() })
        m:join(1, 'a', 0); m:join(2, 'b', 0); m:start(0); m:tick(10)
        T.eq(m:registerDeath(99, 1, 11), nil)
        T.eq(m:registerDeath(2, 99, 11), 'suicide', 'un asesino de fuera no puntúa')
    end)
    T.it('empate entre equipos', function()
        local P = load()
        local m = P.Match.new({ id = 1, mode = P.Modes.get('tdm'), arena = arenaCombat() })
        m:join(1, 'a', 0); m:join(2, 'b', 0); m:start(0); m:tick(10)
        m:finish('time', 20)
        T.eq(m.winner.type, 'draw')
    end)
    T.it('el anfitrión pasa al siguiente jugador más antiguo', function()
        local P = load()
        local m = P.Match.new({ id = 1, mode = P.Modes.get('ffa'), arena = arenaCombat() })
        m:join(5, 'a', 0); m:join(7, 'b', 0); m:join(6, 'c', 0)
        T.eq(m.host, 5)
        m:leave(5)
        T.eq(m.host, 7)
    end)
    T.it('rechaza unirse a una carrera empezada', function()
        local P = load()
        local m = P.Match.new({ id = 1, mode = P.Modes.get('race'), arena = arenaRace() })
        m:join(1, 'a', 0); m:start(0); m:tick(10)
        local ok, err = m:join(2, 'b', 11)
        T.falsy(ok); T.truthy(err:find('no admite'))
    end)
end)

T.describe('Rey de la colina', function()
    T.it('suma puntos al equipo que controla la zona en solitario', function()
        local P = load()
        local m = P.Match.new({ id = 1, mode = P.Modes.get('koth'), arena = arenaCombat() })
        m:join(1, 'a', 0); m:join(2, 'b', 0)  -- 1 → equipo 1, 2 → equipo 2
        m:start(0); m:tick(10)
        local inside, outside = { x = 100, y = 100, z = 10 }, { x = 0, y = 0, z = 0 }
        m:tick(11, { positions = { [1] = inside, [2] = outside } })
        m:tick(13, { positions = { [1] = inside, [2] = outside } })
        T.eq(m.teamScores[1], 3); T.eq(m.zoneOwner, 1)
    end)
    T.it('zona disputada: nadie puntúa', function()
        local P = load()
        local m = P.Match.new({ id = 1, mode = P.Modes.get('koth'), arena = arenaCombat() })
        m:join(1, 'a', 0); m:join(2, 'b', 0)
        m:start(0); m:tick(10)
        local inside = { x = 101, y = 99, z = 11 }
        m:tick(15, { positions = { [1] = inside, [2] = inside } })
        T.eq(m.teamScores[1], 0); T.eq(m.teamScores[2], 0); T.eq(m.zoneOwner, -1)
    end)
    T.it('ignora jugadores muy por encima o debajo de la zona', function()
        local P = load()
        local m = P.Match.new({ id = 1, mode = P.Modes.get('koth'), arena = arenaCombat() })
        m:join(1, 'a', 0); m:join(2, 'b', 0); m:start(0); m:tick(10)
        m:tick(12, { positions = { [1] = { x = 100, y = 100, z = 80 } } })
        T.eq(m.teamScores[1], 0)
    end)
end)

T.describe('Carrera', function()
    T.it('exige checkpoints en orden, cuenta vueltas y registra la llegada', function()
        local P = load()
        local m = P.Match.new({ id = 1, mode = P.Modes.get('race'), arena = arenaRace() })
        m:join(1, 'a', 0); m:join(2, 'b', 0)
        m:start(0); m:tick(10)
        T.falsy(m:reachCheckpoint(1, 2, 11), 'fuera de orden')
        for lap = 1, 2 do
            for cp = 1, 3 do
                local ok, info = m:reachCheckpoint(1, cp, 10 + lap * 10 + cp)
                T.truthy(ok, ('vuelta %d cp %d'):format(lap, cp))
                if lap == 1 and cp == 3 then T.truthy(info.lapCompleted) end
            end
        end
        local p = m.players[1]
        T.truthy(p.finished); T.eq(p.position, 1); T.eq(p.finishTime, 33 - 10)
        T.eq(m.state, 'running', 'falta el segundo corredor')
        local ev = m:tick(33 + 45)
        T.eq(ev[1].reason, 'grace')
        T.eq(m.winner.id, 1)
    end)
    T.it('termina cuando llegan todos', function()
        local P = load()
        local m = P.Match.new({ id = 1, mode = P.Modes.get('race'), arena = arenaRace() })
        m:join(1, 'a', 0); m:start(0); m:tick(10)
        for _ = 1, 2 do for cp = 1, 3 do m:reachCheckpoint(1, cp, 20) end end
        T.eq(m.state, 'ended'); T.eq(m.endReason, 'all_finished')
    end)
    T.it('clasifica por vuelta y checkpoint a quien no ha terminado', function()
        local P = load()
        local m = P.Match.new({ id = 1, mode = P.Modes.get('race'), arena = arenaRace() })
        m:join(1, 'a', 0); m:join(2, 'b', 0); m:start(0); m:tick(10)
        m:reachCheckpoint(2, 1, 11); m:reachCheckpoint(2, 2, 12)
        m:reachCheckpoint(1, 1, 11)
        T.eq(m:standings()[1].id, 2)
    end)
end)

T.describe('Lobby', function()
    T.it('asigna buckets únicos y los libera al borrar', function()
        local P = load()
        local l = P.Lobby.new({ bucketBase = 1000, maxMatches = 2 })
        local a = l:create('ffa', arenaCombat(), 1, 0)
        local b = l:create('tdm', arenaCombat(), 1, 0)
        T.eq(a.bucket, 1000); T.eq(b.bucket, 1001)
        local c, err = l:create('ffa', arenaCombat(), 1, 0)
        T.falsy(c); T.truthy(err:find('hueco'))
        l:remove(a.id)
        T.eq(l:create('ffa', arenaCombat(), 1, 0).bucket, 1000)
    end)
    T.it('al unirse a otra partida abandona la anterior', function()
        local P = load()
        local l = P.Lobby.new()
        local a = l:create('ffa', arenaCombat(), 1, 0)
        local b = l:create('ffa', arenaCombat(), 1, 0)
        T.truthy(l:join(a.id, 1, 'a', 0))
        local ok, _, prev = l:join(b.id, 1, 'a', 0)
        T.truthy(ok); T.eq(prev, a)
        T.eq(a:playerCount(), 0); T.eq(l:findByPlayer(1), b)
    end)
    T.it('rechaza modos y arenas inválidos', function()
        local P = load()
        local l = P.Lobby.new()
        T.falsy(l:create('nope', arenaCombat(), 1, 0))
        local m, err = l:create('race', arenaCombat(), 1, 0)
        T.falsy(m); T.truthy(err:find('Arena no válida'))
    end)
end)
